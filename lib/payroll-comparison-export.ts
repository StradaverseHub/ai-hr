/** Native OOXML and multilingual PDF serializers over the SAME authorized comparison result. */
import * as XLSX from 'xlsx';
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';
import { bestFaceFor, embedPayslipFaces, payslipFaceScripts } from './payslip-pdf-fonts';
import { payrollAmountMinor } from './payroll-period-comparison';
import { payrollComparisonColumns, payrollComparisonCell, PAYROLL_REASON_LABELS, PAYROLL_COMPARISON_BASIS, type PayrollComparisonTranslate } from './payroll-comparison-presentation';
import type { runPayrollComparisonReport } from '../core/custom-reports';
type Run=Awaited<ReturnType<typeof runPayrollComparisonReport>>;
const EXPORT_TEXT={
  report:'Report',payItem:'Pay item',generatedBy:'Generated by',generatedAt:'Generated at',
  runSelection:'Run selection',companyIds:'Company IDs',reasonFilter:'Reason filter',comparisonRows:'Comparison rows',displayedRows:'Displayed rows',
  previousHeadcount:'Previous headcount',currentHeadcount:'Current headcount',joiners:'Verified joiners',leavers:'Verified leavers',
  availability:'Availability',available:'Available',provisional:'Provisional',historicalCurrency:'Historical currency',
  unknownCurrencies:'Unknown currencies remain separate by employer. Variances are unavailable.',recordedCurrencies:'Recorded payroll-result currencies',
  datedContext:'Dated context',datedEvidence:'Dated assignment and Movement evidence',sourceRun:'Source run',requiresRecalculation:'Requires recalculation',
  basis:'Basis',unknownEmployer:'Unknown-currency employer',summary:'Summary',details:'Details',summaryContinued:'Summary continued',
  detailBand:'Details · column band {band}/{bands}',row:'Row',provisionalPayroll:'Provisional payroll',
  footer:'Generated by {name} on {at}',unavailableDetails:'Comparison unavailable; see Summary.',
  periodCaption:'Payroll period comparison · {previous} → {current}',
  totalCaption:'{currency}: {previous} → {current}; variance {variance} ({percentage}%)',
} as const;
function exportText(t:PayrollComparisonTranslate|undefined,key:keyof typeof EXPORT_TEXT,values?:Record<string,string|number>){
  if(t)return t('exports.'+key,values);
  return EXPORT_TEXT[key].replace(/\{(\w+)\}/g,(_,name:string)=>String(values?.[name]??'{'+name+'}'));
}
function metadata(run:Run,t?:PayrollComparisonTranslate):(string|number|null)[][]{
  const summary=run.result.summary,c=(key:keyof typeof EXPORT_TEXT)=>exportText(t,key);
  const label=(key:string,fallback:string)=>t?t(key):fallback;
  const runType=(value:string)=>label('runTypes.'+value,value),runState=(value:string)=>label('runStates.'+value,value);
  return [
    [c('report'),run.name],[c('payItem'),run.definition.payItemCode],[c('generatedBy'),run.generatedBy],[c('generatedAt'),run.generatedAt],
    [label('previousPeriod','Previous period'),run.filters.previousPeriod],[label('currentPeriod','Current period'),run.filters.currentPeriod],[c('runSelection'),run.filters.runType==='all'?label('allRuns','All runs'):runType(run.filters.runType)],
    [c('companyIds'),run.companyIds.join(', ')],[label('department','Department'),run.filters.departmentId??label('allDepartments','All authorised departments')],
    [label('minimum','Minimum absolute variance'),run.filters.minVariance],[label('onlyVariances','Only variances'),run.filters.onlyVariances?label('yes','Yes'):label('no','No')],[c('reasonFilter'),run.filters.reason?label(run.filters.reason==='incrementPromotion'?'incrementPromotion':run.filters.reason==='prorated'?'prorated':'reasons.'+run.filters.reason,run.filters.reason):label('allReasons','All')],
    [c('comparisonRows'),run.result.comparisonRows],[c('displayedRows'),run.result.displayedRows],
    [c('previousHeadcount'),summary?.previousHeadcount??null],[c('currentHeadcount'),summary?.currentHeadcount??null],
    [c('joiners'),summary?.joiners??null],[c('leavers'),summary?.leavers??null],[label('needsReview','Needs review'),summary?.unexplained??null],
    [c('availability'),run.result.available?c('available'):label('unavailable','Unavailable')+': '+run.result.issues.map(issue=>label('issues.'+issue.code,issue.code)+' / '+issue.period+' / '+issue.companyId).join('; ')],
    [c('provisional'),run.result.provisional?label('provisional','Current payroll is processed, not closed. Figures may change.'):label('no','No')],
    [c('historicalCurrency'),run.result.summary?.totals.some(total=>!total.currency)?c('unknownCurrencies'):c('recordedCurrencies')],
    [c('datedContext'),run.contextUnavailable?label('contextUnavailable','Some historical placement or grade evidence is unavailable.'):c('datedEvidence')],
    ...run.result.runs.map(batch=>[c('sourceRun'),`${batch.id} / ${batch.companyId} / ${batch.period} / ${runType(batch.runType)} / ${runState(batch.status)}${batch.stale?' / '+c('requiresRecalculation'):''}`]),
    [label('incrementPromotion','Increment / Promotion'),run.result.reasonFilterCounts.incrementPromotion],[label('prorated','Prorated'),run.result.reasonFilterCounts.prorated],
    ...Object.entries(run.result.reasonCounts).map(([reason,count])=>[label('reasons.'+reason,PAYROLL_REASON_LABELS[reason as keyof typeof PAYROLL_REASON_LABELS]),count]),
    [c('basis'),label('basis',PAYROLL_COMPARISON_BASIS)],
  ];
}
/** Excel preserves 15 significant decimal digits. Refuse a larger value instead of rounding paid money. */
function excelNumber(text:string):number{
  const minor=payrollAmountMinor(text),absolute=minor<BigInt('0')?-minor:minor;
  if(absolute>BigInt('999999999999999'))throw new Error('An amount exceeds Excel’s exact 15-digit precision. Narrow this report or use PDF.');
  return Number(text);
}
/** Excel's cell limit is UTF-16 characters. Refuse rather than silently truncate recorded text. */
function excelText(value:string){
  if(value.length>32767)throw new Error('A recorded text value exceeds Excel’s 32,767-character cell limit. Narrow this report or use PDF.');
  return value;
}
async function excel(run:Run,t?:PayrollComparisonTranslate):Promise<Uint8Array>{
  const columns=payrollComparisonColumns(run.definition,t),book=XLSX.utils.book_new();
  const rows=metadata(run,t).map(row=>row.map(value=>typeof value==='string'?excelText(value):value)),summary=XLSX.utils.aoa_to_sheet(rows);
  let at=rows.length+2;
  const headers=[t?t('columns.currency'):'Currency',exportText(t,'unknownEmployer'),...(['previous','current','variance','variancePct'] as const).map(id=>t?t('columns.'+id):({previous:'Previous amount',current:'Current amount',variance:'Variance',variancePct:'Variance %'}[id]))];
  XLSX.utils.sheet_add_aoa(summary,[headers],{origin:at++});
  for(const total of run.result.summary?.totals??[]){
    const values=[total.currency??(t?t('currencyUnknown'):'Not recorded'),total.companyId??'',total.previous,total.current,total.variance,total.variancePct];
    values.forEach((value,index)=>summary[XLSX.utils.encode_cell({r:at,c:index})]=index>=2&&value!==null?{t:'n',v:excelNumber(value),z:index===5?'0.00"%"':total.currency?`"${total.currency==='MYR'?'RM':total.currency}" #,##0.00`:'0.00'}:{t:'s',v:excelText(value??(t?t('notAvailable'):'N/A'))});at++;
  }
  summary['!ref']=XLSX.utils.encode_range({s:{r:0,c:0},e:{r:Math.max(at-1,rows.length-1),c:5}});
  summary['!cols']=[{wch:28},{wch:75},...Array.from({length:4},()=>({wch:22}))];
  const details=XLSX.utils.aoa_to_sheet([columns.map(column=>column.label)]);
  for(const [index,row] of run.result.rows.entries())for(const [columnIndex,column] of columns.entries()){
    const value=payrollComparisonCell(row,column.id,t),address=XLSX.utils.encode_cell({r:index+1,c:columnIndex});
    details[address]=column.numeric&&value!==null?{t:'n',v:excelNumber(value),z:column.id==='variancePct'?'0.00"%"':row.currency?`"${row.currency==='MYR'?'RM':row.currency}" #,##0.00`:'0.00'}:{t:'s',v:excelText(value??(t?t('notAvailable'):'N/A'))};
  }
  details['!ref']=XLSX.utils.encode_range({s:{r:0,c:0},e:{r:run.result.rows.length,c:columns.length-1}});
  details['!cols']=columns.map(column=>({wch:column.id==='remarks'?70:column.id==='employeeName'?30:22}));
  details['!autofilter']={ref:details['!ref']};
  XLSX.utils.book_append_sheet(book,summary,'Summary');XLSX.utils.book_append_sheet(book,details,'Details');
  return XLSX.write(book,{type:'buffer',bookType:'xlsx'});
}
async function pdf(run:Run,t?:PayrollComparisonTranslate):Promise<Uint8Array>{
  const columns=payrollComparisonColumns(run.definition,t),data=run.result.rows.map(row=>Object.fromEntries(columns.map(column=>[column.id,payrollComparisonCell(row,column.id,t)??(t?t('notAvailable'):'N/A')])));
  const meta=metadata(run,t).map(row=>row.filter(value=>value!==null).join(': '));
  const allStrings=['→',run.name,run.generatedBy,...meta,...data.flatMap(row=>Object.values(row)),...columns.map(column=>column.label)];
  const doc=await PDFDocument.create(),regular=await doc.embedFont(StandardFonts.Helvetica),bold=await doc.embedFont(StandardFonts.HelveticaBold);
  const scripts=payslipFaceScripts(allStrings);
  // The fixed period arrow is absent from the committed Latin face and present in the CJK face.
  // Subset that existing face even for ASCII-only records; retain the shared payslip font behavior.
  if(!scripts.includes('cjk'))scripts.push('cjk');
  const faces=await embedPayslipFaces(doc,scripts);
  const segments=new Intl.Segmenter('en',{granularity:'grapheme'});
  const fontRuns=(text:string,strong=false)=>{
    const result:{text:string;font:PDFFont}[]=[];
    for(const {segment} of segments.segment(text.replace(/\r/g,''))){
      const face=bestFaceFor(segment,faces),font=face?(strong?face.bold:face.regular):strong?bold:regular;
      try{font.encodeText(segment);}catch{throw new Error('A recorded character is unsupported by the PDF fonts. Export Excel to retain it.');}
      const previous=result.at(-1);if(previous?.font===font)previous.text+=segment;else result.push({text:segment,font});
    }return result;
  };
  const measure=(text:string,strong=false,size=8)=>fontRuns(text,strong).reduce((width,run)=>width+run.font.widthOfTextAtSize(run.text,size),0);
  const wrap=(text:string,width:number,strong=false)=>{
    const lines:string[]=[];let line='';
    for(const {segment}of segments.segment(text)){if(segment==='\n'){lines.push(line);line='';continue;}
      if(line&&measure(line+segment,strong)>width){lines.push(line);line=segment;}else line+=segment;}
    lines.push(line);return lines;
  };
  const size:[number,number]=[841.89,595.28],margin=30,width=size[0]-margin*2;
  let page:PDFPage,y=0;
  const draw=(text:string,x:number,yy:number,strong=false,fontSize=8)=>{for(const run of fontRuns(text,strong)){page.drawText(run.text,{x,y:yy,font:run.font,size:fontSize,color:rgb(.12,.15,.2)});x+=run.font.widthOfTextAtSize(run.text,fontSize);}};
  const start=(caption:string)=>{if(doc.getPageCount()>=1000)throw new Error('This PDF exceeds 1000 pages. Narrow the report.');page=doc.addPage(size);y=size[1]-margin;for(const line of wrap(run.name,width,true)){draw(line,margin,y,true);y-=12;}draw(caption,margin,y);y-=16;};
  start(exportText(t,'periodCaption',{previous:run.filters.previousPeriod??'',current:run.filters.currentPeriod??''}));
  for(const line of meta)for(const text of wrap(line,width)){if(y<margin+45)start(exportText(t,'summaryContinued'));draw(text,margin,y);y-=11;}
  for(const total of run.result.summary?.totals??[]){
    const caption=exportText(t,'totalCaption',{currency:total.currency??(t?t('currencyUnknown'):'Currency not recorded')+' / '+total.companyId,previous:total.previous,current:total.current,variance:total.variance??(t?t('notAvailable'):'unavailable'),percentage:total.variancePct??(t?t('notAvailable'):'N/A')});
    for(const text of wrap(caption,width,true)){if(y<margin+45)start(exportText(t,'summaryContinued'));draw(text,margin,y,true);y-=11;}
  }
  const fixed=['currency','previous','current','variance','reason'],rest=columns.filter(column=>!fixed.includes(column.id));
  const bands=Array.from({length:Math.max(1,Math.ceil(rest.length/3))},(_,index)=>[...rest.slice(index*3,index*3+3),...fixed.map(id=>columns.find(column=>column.id===id)!)]);
  for(const [bandIndex,band]of bands.entries()){
    const cellWidth=(width-28)/band.length;
    const header=()=>{
      start(exportText(t,'detailBand',{band:bandIndex+1,bands:bands.length})+(run.result.provisional?' · '+exportText(t,'provisionalPayroll'):''));
      draw(exportText(t,'row'),margin,y,true);let x=margin+28;
      const headings=band.map(column=>wrap(column.label,cellWidth-8,true));
      headings.forEach(lines=>{lines.forEach((line,index)=>draw(line,x+4,y-index*10,true));x+=cellWidth;});
      y-=Math.max(...headings.map(lines=>lines.length))*10+8;
    };
    header();
    for(const [rowIndex,row]of data.entries()){
      const lines=band.map(column=>wrap(row[column.id],cellWidth-8));
      const length=Math.max(...lines.map(value=>value.length));let offset=0;
      do{
        const capacity=Math.floor((y-margin-35)/10);if(capacity<1){header();continue;}
        const take=Math.min(capacity,length-offset);
        draw(String(rowIndex+1),margin,y);let x=margin+28;
        lines.forEach(value=>{value.slice(offset,offset+take).forEach((line,index)=>draw(line,x+4,y-index*10));x+=cellWidth;});
        y-=take*10+8;offset+=take;
        if(offset<length)header();
      }while(offset<length);
    }
    if(!data.length)draw(run.result.available?(t?t('noRows'):'No rows match the selected filters.'):exportText(t,'unavailableDetails'),margin,y);
  }
  const pages=doc.getPages();
  const footer=exportText(t,'footer',{name:run.generatedBy,at:run.generatedAt});
  pages.forEach((value,index)=>{page=value;const lines=wrap(footer,width-65);if(lines.length>3)throw new Error('Preparer metadata is too long for the PDF footer.');lines.forEach((line,lineIndex)=>draw(line,margin,margin-5-lineIndex*8,false,7));draw(`${index+1} / ${pages.length}`,size[0]-margin-50,margin-5,false,7);});
  return doc.save();
}
export async function serializePayrollComparison(run:Run,format:'xlsx'|'pdf',t?:PayrollComparisonTranslate){
  if(run.result.rows.length!==run.result.displayedRows)throw new Error('Export requires the complete filtered comparison.');
  const bytes=format==='xlsx'?await excel(run,t):await pdf(run,t);
  return {bytes,contentType:format==='xlsx'?'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet':'application/pdf',
    filename:'payroll-period-comparison-'+run.filters.currentPeriod+'.'+format};
}
