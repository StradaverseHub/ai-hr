export const TODAY_CATALOGUES: Readonly<Record<AppLocaleCode, Catalogue>> = { en, ms, zh, ta, th, vi };

/** Today copy in the person's language, English for a missing or blank entry; `{name}` placeholders are filled from `vars`. */
export function tt(key: TodayKey, vars: Record<string, string | number> = {}): string {
  const table = TODAY_CATALOGUES[appLocale()] ?? en;
  return (table[key] || en[key]).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
