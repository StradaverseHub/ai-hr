def convert_style_text(txt, sel="", fallback=False, where=""):
    """An inline style body: `prop: value; prop: value` (Jinja tags are left alone)."""
    out = []
    # split on ; that are not inside {{ }} / {% %} / parentheses
    parts, depth_j, depth_p, cur = [], 0, 0, []
    i = 0
    while i < len(txt):
        two = txt[i:i + 2]
        if two in ("{{", "{%"):
            depth_j += 1
            cur.append(two)
            i += 2
            continue
        if two in ("}}", "%}"):
            depth_j = max(0, depth_j - 1)
            cur.append(two)
            i += 2
            continue
        ch = txt[i]
        if ch == "(":
            depth_p += 1
        elif ch == ")":
            depth_p = max(0, depth_p - 1)
        if ch == ";" and not depth_j and not depth_p:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
        i += 1
    parts.append("".join(cur))
    res = []
    for p in parts:
        if ":" not in p:
            res.append(p)
            continue
        prop, val = p.split(":", 1)
        pr = re.sub(r"\{%.*?%\}|\{\{.*?\}\}", "", prop, flags=re.S).strip()   # a Jinja tag may stand before the name
        if not re.match(r"^[-\w]+$", pr):
            res.append(p)
            continue
        # Jinja inside the value: literal colours outside tags are rewritten; inside a {{ }} string, a colour in quotes is too
        segs = re.split(r"(\{\{.*?\}\}|\{%.*?%\})", val, flags=re.S)
        nv = []
        for sg in segs:
            if sg.startswith("{%"):
                nv.append(sg)
            elif sg.startswith("{{"):
                nv.append(re.sub(r"(['\"])((?:(?!\1).)*)\1", lambda m: m.group(1) + convert_value_masked(pr, m.group(2), m.group(2), sel, fallback, where) + m.group(1)
                                 if COL.search(m.group(2)) or VARUSE.search(m.group(2)) else m.group(0), sg))
            else:
                nv.append(convert_value_masked(pr, sg, sg, sel, fallback, where))
        res.append(prop + ":" + "".join(nv))
    return ";".join(res)


JINJA_LIT = re.compile(r"(\{\{[^{}]*?)(['\"])(" + HEXRE + r")\2")


# a name the old files read with a fallback while nothing defined it (the fallback was always what drew): the table now
# defines --surface-2, so the wrapper goes and the fallback colour stays, or light would change
UNDEFINED_WRAPPERS = re.compile(r"var\(--(?:surface-2|border)\s*,\s*(" + HEXRE + r")\s*\)", re.I)


def convert_template(text, where, fallback=False):
    text = UNDEFINED_WRAPPERS.sub(lambda m: m.group(1), text)
    # <style> blocks
    def blk(m):
        return m.group(1) + convert_css(m.group(2), where=where, fallback=fallback, skip_print=True) + m.group(3)
    text = STYLE_BLOCK.sub(blk, text)

    # style="" attributes
    def attr(m):
        q = m.group(2)[0]
        body = m.group(3) if m.group(3) is not None else m.group(4)
        if not (COL.search(body) or VARUSE.search(body)):
            return m.group(0)
        new = convert_style_text(body, where=where, fallback=fallback)
        return m.group(1) + q + new + q
    text = STYLE_ATTR.sub(attr, text)

    # svg presentation attributes
    def svg(m):
        c = parse(m.group(3))
        nm = REG.token_for("fg", c)
        STATS["colours -> tokens"] += 1
        return m.group(1) + m.group(2) + ("var(--%s, %s)" % (nm, canon(c)) if fallback else "var(--%s)" % nm) + m.group(2)
    text = SVG_ATTR.sub(svg, text)

    # JS that sets a style: 'padding:10px 0;border-bottom:1px solid #eef0f5'
    def sets(m):
        q = m.group(2)
        body = m.group(3)
        if not COL.search(body) and not VARUSE.search(body):
            return m.group(0)
        if m.group(1).rstrip().endswith("cssText =") or "cssText" in m.group(1):
            return m.group(1) + q + convert_style_text(body, where=where, fallback=fallback) + q
        prop = re.search(r"style\.(\w+)", m.group(1)).group(1)
        prop = {"backgroundColor": "background-color", "borderColor": "border-color"}.get(prop, prop)
        return m.group(1) + q + convert_value_masked(prop, body, body, "", fallback, where) + q
    text = SETSTYLE.sub(sets, text)
    return text


