def role_of(prop, selector=""):
    p = prop.lower()
    if p.startswith("--"):
        return "cv"
    if p in ("color", "-webkit-text-fill-color", "caret-color", "text-decoration-color", "-webkit-text-stroke-color",
             "accent-color", "column-rule-color"):
        return "fg"
    if p in ("fill", "stroke"):
        return "svg"
    if p in ("stop-color", "flood-color", "lighting-color"):
        return "bg"
    if p.startswith("background"):
        return "bg"
    if p.startswith("border") or p.startswith("outline") or p in ("column-rule", "scrollbar-color"):
        return "bd"
    if "shadow" in p or p == "filter" or p == "-webkit-filter":
        return "sh"
    if p in ("mask", "mask-image", "-webkit-mask-image", "-webkit-mask"):
        return None
    return "fg"


class Registry:
    """Every token used, whether table-named or derived."""
    def __init__(self):
        self.derived = {}          # token name -> (light text, dark text, role)
        self.used = collections.Counter()
        self.const = {}            # constants (the top bar and friends)

    def token_for(self, role, c, const=False):
        """-> token name (without --)."""
        hx = canon(c)
        L = lum(*c[:3])
        if role == "svg":
            role = "fg"
        if role == "sh" and c[3] is None:                      # a ring or highlight drawn with box-shadow: a fill or a line
            role = "bg" if L > 0.8 else "bd"
        if const:
            nm = "k-" + key(c)
            self.const[nm] = hx
            self.used[nm] += 1
            return nm
        if c[3] is None and role != "cv":
            nm = NAMED.get((role, hx))
            if nm:
                self.used[nm] += 1
                return nm
        if (role == "bg" and hx == canon(parse(LIGHT["overlay"]))) or (role == "sh" and hx == canon(parse(LIGHT["shadow"]))):
            nm = "overlay" if role == "bg" else "shadow"
            self.used[nm] += 1
            return nm
        pre = {"fg": "fg", "bg": "bg", "bd": "bd", "sh": "sh", "cv": "cv"}.get(role, "x")
        nm = "d-%s-%s" % (pre, key(c))
        if nm not in self.derived:
            self.derived[nm] = dark_entry(role, c)
        self.used[nm] += 1
        return nm


def dark_role(role, c):
    """A custom property's colour has no property to read: a pale one is a fill, a mid-tone one stays, a deep one is text."""
    if role != "cv":
        return role
    L = lum(*c[:3])
    return "bg" if L > 0.7 else ("const" if L > 0.12 else "fg")


def dark_entry(role, c):
    hx = canon(c)
    d = DERIVED_OVERRIDE.get(key(c) + ":" + role) or derive_dark(dark_role(role, c), c)
    if isinstance(d, str):
        return (hx, d, role)
    return (hx, canon(d) if len(d) == 4 else hexof(*d), role)


