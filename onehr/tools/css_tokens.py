# a CSS scanner: comments, strings and url() bodies masked; declarations found with their selector
# ---------------------------------------------------------------------------------------------------------------------
def mask(t):
    out, i, n = [], 0, len(t)
    while i < n:
        c = t[i]
        if t.startswith("/*", i):
            j = t.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append("\x01" * (j - i))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and t[j] != c:
                j += 2 if t[j] == "\\" else 1
            j += 1
            out.append("\x02" * (j - i))
            i = j
        elif t.startswith("url(", i):
            q = t[i + 4:i + 5]
            if q in "\"'" and q:
                k = i + 5
                while k < n and t[k] != q:
                    k += 2 if t[k] == "\\" else 1
                j = t.find(")", k)
            else:
                j = t.find(")", i)
            out.append(t[i:i + 4])
            out.append("\x02" * (j - i - 4))
            out.append(")")
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def print_spans(t):
    spans = []
    for m in re.finditer(r"@media\s+print\s*\{", t):
        i, d = m.end(), 1
        while i < len(t) and d:
            d += (t[i] == "{") - (t[i] == "}")
            i += 1
        spans.append((m.start(), i))
    return spans


def declarations(css):
    """-> masked text, [(start, end, selector)] of each declaration (prop: value, without the ; )."""
    m = mask(css)
    stack, pre, res = [], 0, []
    for i, c in enumerate(m):
        if c == "{":
            stack.append(m[pre:i].strip())
            pre = i + 1
        elif c == "}":
            if stack and m[pre:i].strip():
                res.append((pre, i, stack[-1]))
            if stack:
                stack.pop()
            pre = i + 1
        elif c == ";":
            if stack:
                res.append((pre, i, stack[-1]))
            pre = i + 1
    return m, res


def selector_const(sel):
    """True when every selector in the list sits in the top bar's own paint (its menus and the Account menu body do not)."""
    if not sel or sel.startswith("@"):
        return False
    parts = [p.strip() for p in re.split(r",(?![^(]*\))", sel) if p.strip()]
    return bool(parts) and all(TOPBAR_SEL.search(p) and not MENU_SEL.search(p) for p in parts)


