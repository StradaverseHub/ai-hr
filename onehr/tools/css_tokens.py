NAMEDCOL = {"white": "#ffffff", "black": "#000000"}
HEXRE = r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![0-9a-zA-Z_-])"
RGBRE = r"rgba?\(\s*(?!var\()[^()]*\)"
COL = re.compile(r"(?<![\w&\-])(?:" + HEXRE + r"|" + RGBRE + r"|(?<![-\w.#$])(?:white|black)(?![-\w(]))", re.I)


def parse(lit):
    """-> (r, g, b, a or None). a is the text of the alpha as written (None = opaque)."""
    s = lit.strip().lower()
    if s in NAMEDCOL:
        s = NAMEDCOL[s]
    if s.startswith("#"):
        h = s[1:]
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = None if len(h) == 6 else round(int(h[6:8], 16) / 255, 3)
        return r, g, b, a
    m = re.match(r"rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)", s)
    if not m:
        return None
    r, g, b = (int(round(float(m.group(i)))) for i in (1, 2, 3))
    a = m.group(4)
    if a is not None:
        a = float(a[:-1]) / 100 if a.endswith("%") else float(a)
        if a >= 1:
            a = None
    return r, g, b, a


def fmt_a(a):
    t = ("%.3f" % a).rstrip("0").rstrip(".")
    return t if not t.startswith("0.") else t[1:]


def hexof(r, g, b):
    return "#%02x%02x%02x" % (r, g, b)


def canon(c):
    """The colour's canonical light text: '#rrggbb', or 'rgba(r, g, b, .a)'."""
    r, g, b, a = c
    return hexof(r, g, b) if a is None else "rgba(%d, %d, %d, %s)" % (r, g, b, fmt_a(a))


def key(c):
    r, g, b, a = c
    return "%02x%02x%02x" % (r, g, b) + ("" if a is None else "-a" + fmt_a(a).lstrip("."))


def lum(r, g, b):
    f = lambda v: (lambda x: x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4)(v / 255)  # noqa: E731
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def ratio(l1, l2):
    hi, lo = max(l1, l2), min(l1, l2)
    return (hi + 0.05) / (lo + 0.05)


def hls(r, g, b):
    return colorsys.rgb_to_hls(r / 255, g / 255, b / 255)


def from_hls(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, max(0, min(1, l)), max(0, min(1, s)))
    return int(round(r * 255)), int(round(g * 255)), int(round(b * 255))


SURFACE_L = lum(0x18, 0x1c, 0x2e)
# text on the dark page must stay readable on its raised grounds too (surface-3, a dark tint): 6.0 on the page leaves 4.5 there
FG_FLOOR = 6.0


def solve_l(h, s, target_lum):
    """The lightness (0..1) of colour (h, s) whose luminance is closest to target_lum."""
    lo, hi = 0.0, 1.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if lum(*from_hls(h, mid, s)) < target_lum:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def with_alpha(rgb, a):
    return rgb + (a,)


