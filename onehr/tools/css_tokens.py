#!/usr/bin/env python3
"""css_tokens.py: put every colour in OneHR's CSS on a token, so the Theme setting (html[data-theme]) can repaint the product.

    python3 tools/css_tokens.py            convert in place (the repo this file lives in)
    python3 tools/css_tokens.py --dry      count only, change nothing
    python3 tools/css_tokens.py --check    exit 1 when anything is left to convert (the lint test uses the same rules)
    python3 tools/css_tokens.py --report <file.json>   also write the full report (every derived token, what stayed literal)
    python3 tools/css_tokens.py <root>     another checkout (a QC copy, a branch worktree)

THE ONE SOURCE. `TOKENS` below is the table (names follow canvas board C1): a name, its light value, its dark value. The script
writes three generated regions at the top of `static/style.css`, between the css_tokens:begin / :end marks, and never anything else
by hand: the light `:root` block, the dark block on `html[data-theme=dark]` and the same dark block inside
`@media (prefers-color-scheme: dark){ html[data-theme=auto] }`. Both dark blocks sit in `@media screen`, so print is always light.

WHAT IT DOES to `static/style.css` and the inline styles / <style> blocks / svg fill and stroke of `templates/*.html`:
  * every colour (hex, rgb(), rgba(), white / black) becomes `var(--token)` BY EXACT VALUE, so the light build is pixel-identical:
    the token's light value is the very colour it replaced. Near-duplicates (#5f6678 / #6b7186) are never merged.
  * a colour's job is read from its property (and, for a few contexts, its selector): text, fill (background), line (border /
    outline), shadow, svg. The same hex used for text and for a fill is two tokens (a navy text is --accent-ink, a navy fill is
    --accent, the top bar is --topbar).
  * a colour the table does not name gets a token of its own, `--d-<role>-<hex>`, whose dark value is DERIVED by rule (see
    `derive_dark`): hue kept, lightness moved so text keeps its contrast on the dark page, a pale tint becomes a dark tint, a
    mid-tone fill stays. Every derived token is listed in the report.
  * the old names (`--navy`, `--navy-700`, `--navy-600`, `--red`, `--red-700`, `--rl-line`, ...) are expanded into the role
    token where they are read, and kept as aliases so nothing that reads them breaks.
Never touched: email templates and builders (Outlook has no CSS variables), ReportLab PDFs, `@media print` blocks, the colours
inside url(data:...) images, `rgba(var(--x), a)` (a triplet variable), the standalone pages (they carry their own CSS), and
what `STAYS` lists. They are reported, never edited. Idempotent: a colour already a var() never matches. When a branch
merges later, take its CSS as written and run this again (docs: Dark mode and text size plan)."""
