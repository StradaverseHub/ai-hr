VARUSE = re.compile(r"var\(\s*--(" + "|".join(re.escape(k) for k in OLD_VARS) + r")\s*(?:,[^)]*)?\)")


def convert_value(prop, val, sel, fallback=False, where=""):
    """Return the value with every colour a var(--token). `fallback`: var(--token, #light) for files that also ship offline."""
    role = role_of(prop, sel)
    if role is None:
        return val
    const = selector_const(sel)
    # an old name, read here, is expanded to its literal and then mapped like one
    val = VARUSE.sub(lambda m: OLD_VARS[m.group(1)], val)

    def sub(m):
        lit = m.group(0)
        c = parse(lit)
        if c is None:
            UNPLACED.append((where, prop, lit))
            return lit
        # a colour that is only a `transparent` fade (alpha 0) of a colour keeps that colour's role
        nm = REG.token_for(role, c, const=const)
        STATS["colours -> tokens"] += 1
        return ("var(--%s, %s)" % (nm, canon(c))) if fallback else "var(--%s)" % nm

    return COL.sub(sub, val)


def token_light_hex(name):
    """The light colour a token name stands for (table name, or a --d-/--k- name), as canonical text, or None."""
    if name in LIGHT:
        c = parse(LIGHT[name])
        return canon(c) if c else None
    p = parse_token_name(name)
    return canon(p[2]) if p else None


TOKEN_USE = re.compile(r"var\(--([\w-]+)\)")


def apply_const(prop, val, sel):
    """A rule in the top bar's own paint (selector_const): any colour token read there becomes the constant of the same light colour
    (--k-<hex>), so a selector list that grows is put right the same way a new literal is."""
    if not selector_const(sel) or role_of(prop, sel) is None:
        return val

    def fix(m):
        name = m.group(1)
        if name.startswith("k-") or name in ALIASES or name.startswith(("chev-",)):
            return m.group(0)
        hx = token_light_hex(name)
        if not hx:
            return m.group(0)
        c = parse(hx)
        nm = "k-" + key(c)
        REG.const[nm] = canon(c)
        return "var(--%s)" % nm
    return TOKEN_USE.sub(fix, val)


def apply_overrides(prop, val, sel):
    """A rule the OVERRIDES table names: a token that reads as that light hex becomes the override's token (so a rule converted
    earlier, or by a merge, is put right the same way)."""
    for srx, prx, h, n in OVERRIDES_RX:
        if prx.search(prop) and srx.search(sel.strip()):
            def fix(m):
                return "var(--%s)" % n if m.group(1) != n and token_light_hex(m.group(1)) == h else m.group(0)
            val = TOKEN_USE.sub(fix, val)
    return val


def convert_css(css, where="static/style.css", fallback=False, skip_print=True):
    m, ds = declarations(css)
    spans = print_spans(css)
    out, last = [], 0
    for a, b, sel in ds:
        seg_m = m[a:b]
        if ":" not in seg_m:
            continue
        if skip_print and any(x <= a < y for x, y in spans):
            if COL.search(seg_m):
                STATS["print left"] += 1
            continue
        pi = seg_m.index(":")
        prop = seg_m[:pi].replace("\x01", "").strip()      # a comment before the declaration is masked text, not part of its name
        if not re.match(r"^[-\w]+$", prop):
            continue
        vstart = a + pi + 1
        raw = css[vstart:b]
        # the masked value tells us where the colours are; the original text is what is rewritten
        new = apply_overrides(prop, apply_const(prop, raw, sel), sel) if OVERRIDES_RX else apply_const(prop, raw, sel)
        mv = mask(new)
        if COL.search(mv) or VARUSE.search(mv):
            new = convert_value_masked(prop, new, mv, sel, fallback, where)
        if new != raw:
            out.append(css[last:vstart])
            out.append(new)
            last = b
    out.append(css[last:])
    return "".join(out)


def convert_value_masked(prop, raw, mv, sel, fallback, where):
    """Rewrite only the colour spans found in the masked value (url bodies and strings are never touched)."""
    role = role_of(prop, sel)
    if role is None:
        return raw
    const = selector_const(sel)
    pieces, last = [], 0
    spans = []
    for mm in VARUSE.finditer(mv):
        spans.append((mm.start(), mm.end(), "old", mm.group(1)))
    for mm in COL.finditer(mv):
        if any(s <= mm.start() < e for s, e, k, v in spans):
            continue
        if fallback and re.search(r"var\(--[\w-]+\s*,\s*$", mv[:mm.start()]):    # already the fallback of a token (the offline copy)
            continue
        spans.append((mm.start(), mm.end(), "lit", None))
    spans.sort()
    for s, e, kind, name in spans:
        pieces.append(raw[last:s])
        lit = OLD_VARS[name] if kind == "old" else raw[s:e]
        c = parse(lit)
        if c is None:
            UNPLACED.append((where, prop, lit))
            pieces.append(raw[s:e])
        else:
            nm = override_for(sel, prop, c) or REG.token_for(role, c, const=const)
            STATS["colours -> tokens"] += 1
            pieces.append(("var(--%s, %s)" % (nm, canon(c))) if fallback else "var(--%s)" % nm)
        last = e
    pieces.append(raw[last:])
    return "".join(pieces)


