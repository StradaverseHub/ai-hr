# derive_dark: the rule for a colour the table does not name. Deterministic, listed in the report, never a guess at one place.
# ---------------------------------------------------------------------------------------------------------------------
def derive_dark(role, c):
    r, g, b, a = c
    L = lum(r, g, b)
    h, l, s = hls(r, g, b)
    chroma = (max(r, g, b) - min(r, g, b)) / 255
    # grey, or the pale blue-grey family the product's greys live in (hue 198-260 degrees, little colour): one ladder
    neutral = chroma < 0.05 or (0.55 < h < 0.73 and chroma < 0.12)
    if role == "const":
        return c
    if role == "sh":
        if a is not None and L > 0.55 and neutral and a >= 0.5:      # a white glow
            return (0x18, 0x1c, 0x2e, a)
        if a is not None and L > 0.55:
            return c
        if a is not None and s > 0.55 and l > 0.3:                   # a coloured glow (red, green): keeps its colour
            return c
        a2 = min(0.85, 0.12 + (a if a is not None else 0.2) * 2.2)
        return (0, 0, 0, round(a2, 2))
    if role == "bg":
        if a is not None:
            if L > 0.9 and neutral:
                return (0x18, 0x1c, 0x2e, a) if a >= 0.5 else c
            if L < 0.12 and a >= 0.3:                                 # a scrim behind a dialog or drawer: darker still, never a wash
                return (0, 0, 0, round(min(a + 0.2, 0.85), 2))
            if L < 0.12 and neutral:                                  # a dark wash: becomes a light wash of the same strength
                return (255, 255, 255, round(min(a * 1.15, 0.9), 3))
            if s > 0.3 and L < 0.12:                                  # a navy wash: the accent, lighter
                return (0x9a, 0xa6, 0xff, round(min(a * 1.2, 0.9), 3))
            if L > 0.6:
                return (0x2d, 0x33, 0x50, a)
            return c
        if L > 0.6 or (L > 0.4 and l > 0.72):                        # a light neutral or tint (a pale blue-grey chip at L .55 too)
            if neutral:
                if L >= 0.90:
                    return (0x1e, 0x23, 0x38)
                return (0x26, 0x2b, 0x44)
            ts = min(max(s * 0.6, 0.2), 0.55)
            tl = min(0.19, max(0.10, 0.10 + 0.10 * (1 - L) / 0.3))
            return from_hls(h, tl, ts)
        if L <= 0.12:
            if 0.5 < h < 0.8 and s >= 0.3:                            # a deep navy fill that is not the accent itself (the table
                return c                                                  # names --accent and --accent-hover): keeps its colour, white text still reads
            if neutral:
                return (0x2f, 0x36, 0x58)
            return c                                                  # a deep coloured fill (green, red, teal) for white text: unchanged, so the
                                                                      # text keeps the contrast it has today (lifting it cost white text its 4.5:1)
        if neutral and L > 0.25:
            return (0x3c, 0x44, 0x66)                                 # a grey fill (a bar, a disabled field)
        return c                                                      # a mid-tone fill: for white text, or a bar
    if role == "bd":
        if a is not None:
            if L > 0.6 and a >= 0.4:
                return c
            if L < 0.2:
                return (0x9a, 0xa6, 0xff, round(min(a * 1.4, 0.9), 3))
            return c
        if L > 0.55:
            if neutral:
                if L >= 0.86:
                    return (0x2d, 0x33, 0x50)
                return (0x3c, 0x44, 0x66)
            return from_hls(h, 0.27, min(s * 0.5, 0.4))               # a coloured border: same hue, dark
        # a mid or dark border (navy, red, green outline): as readable as a text colour, 3:1 on the page
        return derive_fg_color(r, g, b, floor=3.3)
    # fg and svg
    if a is not None:
        base = derive_fg_color(r, g, b, floor=FG_FLOOR) if L < 0.6 else lift_pale(r, g, b)
        return base + (a,)
    if L >= 0.6:
        return lift_pale(r, g, b) + (None,)                          # white or pale text on a fill: the same, lifted just enough to read on --accent
    return derive_fg_color(r, g, b, floor=FG_FLOOR)


def derive_fg_color(r, g, b, floor=None):
    floor = FG_FLOOR if floor is None else floor
    """Same hue, lightness moved so the colour keeps (at least) the contrast it had on white, on the dark surface."""
    L = lum(r, g, b)
    h, l, s = hls(r, g, b)
    r0 = ratio(1.0, L)                                                # contrast on white today
    target = max(r0, floor)
    target = min(target, 15.0)
    want = target * (SURFACE_L + 0.05) - 0.05                         # luminance giving that ratio on the dark surface
    sat = s * (0.85 if s > 0.6 else 1.0)
    l2 = solve_l(h, sat, want)
    return from_hls(h, l2, sat)


PALE_MIN_LUM = 0.70        # pale text sits on a fill; on --accent (#4B54B0, luminance 0.11) 4.5:1 needs 0.67, so 0.70 leaves a margin


def lift_pale(r, g, b):
    """A pale colour (a light text on a navy fill) mixed toward white until it reads on the dark accent fill; one already light enough is unchanged."""
    if lum(r, g, b) >= PALE_MIN_LUM:
        return (r, g, b)
    lo, hi = 0.0, 1.0
    for _ in range(30):
        mid = (lo + hi) / 2
        if lum(*(int(round(v + (255 - v) * mid)) for v in (r, g, b))) < PALE_MIN_LUM:
            lo = mid
        else:
            hi = mid
    return tuple(int(round(v + (255 - v) * hi)) for v in (r, g, b))


