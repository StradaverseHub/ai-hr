def find_used_tokens(texts):
    """Every --d-* / --k-* token the project reads, so a re-run keeps the ones in files it does not rewrite."""
    found = set()
    for t in texts:
        found.update(re.findall(r"var\(--((?:d-[a-z]+|k)-[0-9a-f]{6}(?:-a[0-9]+)?)", t))
    return found


def parse_token_name(nm):
    m = re.match(r"(?:(d)-([a-z]+)|(k))-([0-9a-f]{6})(?:-a([0-9]+))?$", nm)
    if not m:
        return None
    d, role, k, hx, al = m.groups()
    kind = "d" if d else "k"
    r, g, b = int(hx[0:2], 16), int(hx[2:4], 16), int(hx[4:6], 16)
    a = None if al is None else float("0." + al) if not al.startswith("0.") else float(al)
    return kind, role, (r, g, b, a)


def build_blocks(extra_names):
    """The three generated regions, as one text."""
    # tokens re-read from a re-run (a name found in files, absent from this run's registry) are re-derived from their name
    for nm in sorted(extra_names):
        if nm in REG.derived or nm in REG.const:
            continue
        p = parse_token_name(nm)
        if not p:
            continue
        kind, role, c = p
        if kind == "k":
            REG.const[nm] = canon(c)
        else:
            REG.derived[nm] = dark_entry(role, c)
    light, dark = [], []
    for n, l, d, u in TOKENS:
        light.append("--%s: %s;" % (n, l))
        dark.append("--%s: %s;" % (n, d))
    for old, tgt in ALIASES.items():
        light.append("--%s: var(--%s);" % (old, tgt))
    img_light = ["--%s: %s;" % (n, l) for n, l, d in IMAGE_TOKENS]
    img_dark = ["--%s: %s;" % (n, d) for n, l, d in IMAGE_TOKENS]
    for nm in sorted(REG.const):
        light.append("--%s: %s;" % (nm, REG.const[nm]))
    for nm in sorted(REG.derived):
        l, d, role = REG.derived[nm]
        light.append("--%s: %s;" % (nm, l))
        if d != l:
            dark.append("--%s: %s;" % (nm, d))

    def wrap(lines):
        out, row = [], "  "
        for ln in lines:
            if len(row) + len(ln) > 118:
                out.append(row.rstrip())
                row = "  "
            row += ln + " "
        out.append(row.rstrip())
        return "\n".join(out)
    extra = DARK_EXTRA
    dark_extra = lambda sel: extra.replace(":DARK", sel)  # noqa: E731
    return "\n".join([
        BEGIN,
        "/* Colour tokens (Chris, 2026-11-01: dark mode). Light is today's look; dark is canvas board C1. */",
        ":root {", wrap(light), *img_light, "}",
        "@media screen {",
        "html[data-theme=dark] {", "  color-scheme: dark;", wrap(dark), *img_dark, "}",
        dark_extra("html[data-theme=dark]"),
        "}",
        "@media screen and (prefers-color-scheme: dark) {",
        "html[data-theme=auto] {", "  color-scheme: dark;", wrap(dark), *img_dark, "}",
        dark_extra("html[data-theme=auto]"),
        "}",
        END, ""])


def split_regions(css):
    """-> (before, region or None, after)."""
    a = css.find(BEGIN)
    if a < 0:
        return css, None, ""
    b = css.find(END, a)
    return css[:a], css[a:b + len(END)], css[b + len(END):].lstrip("\n")


