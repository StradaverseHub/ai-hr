import {afterAll,beforeAll,beforeEach,describe,it,expect,vi} from 'vitest';
import {randomUUID} from 'node:crypto';
import {eq} from 'drizzle-orm';
import {hireEmployee,setReportingLine} from '../core/org';
import {assignDefaultShift,createShift,rosterWindowView,rosterExceptionCount} from '../core/roster';
import {checkIn,checkOut} from '../packs/attendance/service';
import {readMyTeam} from '../core/my-team';
import {rosterTeamContext} from '../app/roster/my-team-scope';
import {serializeMyTeamQuery} from '../lib/my-team-query';
import {addDaysIso,weekRangeOf} from '../lib/roster-month';
import {parseCsv} from '../lib/csv';
import {todayInKualaLumpur} from '../lib/hr-date';
import {adminCtx,createAppUser,entitledCtx,owner,seedBase,resetDb,migrateTestDb,closeAll,type Base} from './harness';
import type {SessionContext} from '../db/client';
import * as schema from '../db/schema';
import messages from '../messages/en.json';
const mocks=vi.hoisted(()=>({session:vi.fn()}));
vi.mock('@/lib/scope',()=>({scopedSession:mocks.session}));
vi.mock('next-intl/server',()=>({getLocale:async()=> 'en',getTranslations:async()=> (key:keyof typeof messages.myTeam,values?:Record<string,string|number>)=>{let text=String(messages.myTeam[key]);for(const [name,value] of Object.entries(values??{}))text=text.replace(`{${name}}`,String(value));return text;}}));
import {GET as exportTeam} from '../app/manage/my-team/export/route';
let b:Base,managerCtx:SessionContext,report:{employmentId:string;personId:string},other:{employmentId:string;personId:string},ended:{employmentId:string;personId:string};
const today=todayInKualaLumpur();
const query={view:'week' as const,scope:'direct' as const,anchorDate:today,search:'SUM'};
beforeAll(migrateTestDb);afterAll(closeAll);
beforeEach(async()=>{
 await resetDb();b=await seedBase();const admin=adminCtx(b);
 const hire=(name:string)=>hireEmployee(admin,{person:{fullName:name,primaryEmail:`export_${randomUUID()}@t.local`},companyId:b.companyId,departmentId:b.deptA,employmentType:'full_time',hiredOn:'2024-01-01'});
 const manager=await hire('Export Manager');report=await hire('=SUM(A1)');other=await hire('Other Report');ended=await hire('Not a report');
 const userId=await createAppUser(b.tenantId,manager.personId,'manager');
 managerCtx={...await entitledCtx(b,['manager']),userId,personId:manager.personId,roles:['manager'],grants:[{role:'manager',companyId:b.companyId}]};
 for(const employmentId of [report.employmentId,other.employmentId])await setReportingLine(admin,{subordinateEmploymentId:employmentId,managerEmploymentId:manager.employmentId,lineType:'administrative',validFrom:'2024-01-01'});
 const shiftId=(await createShift(admin,{name:'Actual export shift',code:'EXPORT',startTime:'09:00:00',endTime:'18:00:00',breakMinutes:60,weeklyPattern:[1,2,3,4,5,6,7]})).id;
 for(const employmentId of [report.employmentId,other.employmentId,ended.employmentId])await assignDefaultShift(admin,{employmentId,shiftId});
 await checkIn(admin,{employmentId:report.employmentId,date:today,time:'09:00'});await checkOut(admin,{employmentId:report.employmentId,date:today,time:'18:00'});
 mocks.session.mockResolvedValue({s:managerCtx,scopeIds:[b.companyId]});
});
describe('actual canonical My Team projection flows through export and roster destinations',()=>{
 it('exports the actual filtered grid while whole-team summary remains unchanged',async()=>{
  const snapshot=await readMyTeam(managerCtx,{...query,companyIds:[b.companyId]});
  expect(snapshot.gridEmploymentIds).toEqual([report.employmentId]);expect(snapshot.todaySummary.members).toBe(2);
  const response=await exportTeam(new Request('http://localhost/manage/my-team/export?'+serializeMyTeamQuery(query)));
  expect(response.status).toBe(200);const rows=parseCsv(await response.text());
  expect(rows).toHaveLength(2);expect(rows[1][0]).toBe("'=SUM(A1)");expect(rows.flat().join(' ')).not.toContain('Other Report');expect(rows.flat().join(' ')).not.toContain('Not a report');
  const column=4+snapshot.period.gridDates.indexOf(today);expect(column).toBeGreaterThanOrEqual(4);expect(rows[1][column]).toContain('EXPORT');expect(rows[1][column]).toContain('09:00');expect(rows[1][column]).toContain('18:00');
 });
 it('keeps future-termination roster facts aligned with current team scope while excluding today/past endings',async()=>{
  await owner.db.update(schema.employment).set({terminatedOn:addDaysIso(today,7)}).where(eq(schema.employment.id,report.employmentId));
  await owner.db.update(schema.employment).set({terminatedOn:today}).where(eq(schema.employment.id,other.employmentId));
  await owner.db.update(schema.employment).set({terminatedOn:addDaysIso(today,-1)}).where(eq(schema.employment.id,ended.employmentId));
  const period=weekRangeOf(today);
  const view=await rosterWindowView(adminCtx(b),{companyIds:[b.companyId],employmentIds:[report.employmentId,other.employmentId,ended.employmentId],from:period.from,to:period.to});
  expect(view.employees.map(e=>e.employmentId)).toEqual([report.employmentId]);
  expect(view.allEmployees.map(e=>e.employmentId)).toEqual([report.employmentId]);
  expect(view.usual[report.employmentId]).toBeDefined();
  const snapshot=await readMyTeam(managerCtx,{...query,search:'',companyIds:[b.companyId]});
  expect(snapshot.scope.employmentIds).toEqual([report.employmentId]);
  const employee=snapshot.employees[0];expect(employee.defaultShift?.code).toBe('EXPORT');
  expect(employee.days.find(day=>day.date===today)?.roster).toMatchObject({kind:'shift',code:'EXPORT',shiftId:view.usual[report.employmentId].shiftId});
  expect(employee.weeks.find(week=>week.from===period.from)?.rosteredDays).toBe(7);
 });
 it('recomputes original roster reader scope and narrows dropdowns/count when the team changes',async()=>{
  const params={myTeam:serializeMyTeamQuery(query).toString()};
  const team=(await rosterTeamContext(managerCtx,[b.companyId],params))!;expect(team.scope.employmentIds).toEqual([report.employmentId]);
  const view=await rosterWindowView(managerCtx,{companyIds:team.scope.companyIds,employmentIds:team.scope.employmentIds,from:team.scope.from,to:team.scope.to});
  expect(view.employees.map(e=>e.employmentId)).toEqual([report.employmentId]);expect(view.allEmployees.map(e=>e.employmentId)).toEqual([report.employmentId]);
  await owner.db.update(schema.reportingLine).set({validTo:today}).where(eq(schema.reportingLine.subordinateEmploymentId,report.employmentId));
  const changed=(await rosterTeamContext(managerCtx,[b.companyId],params))!;expect(changed.scope.employmentIds).toEqual([]);
  const empty=await rosterWindowView(managerCtx,{companyIds:changed.scope.companyIds,employmentIds:changed.scope.employmentIds,from:changed.scope.from,to:changed.scope.to});
  expect(empty.employees).toEqual([]);expect(empty.allEmployees).toEqual([]);expect(await rosterExceptionCount(managerCtx,{from:changed.scope.from,to:changed.scope.to,companyIds:changed.scope.companyIds,employmentIds:[]})).toBe(0);
  const response=await exportTeam(new Request('http://localhost/manage/my-team/export?'+serializeMyTeamQuery(query)));expect(response.status).toBe(200);expect(parseCsv(await response.text())).toHaveLength(1);
 });
});
