/** Authored UNRUN; mount at test/helpers/review-body-pending-parent-contract.ts.
 * Real native prepare/retire adapters supply rows; no synthetic parent/receipt/native proof.
 * Fixture writer is owner-defined but is invoked through the actual ai_hr_app LOGIN.
 * Do not mount on staging. Hosted disposable test DB only. */
import {randomUUID} from 'node:crypto';
import {sql} from 'drizzle-orm';
import {expect} from 'vitest';
import {withTenant,type SessionContext,type Tx} from '../../db/client';
import {owner} from '../harness';
import {pgSqlState} from '../../lib/db-error';

const refusal='Review body requires pending parent';
type Pending={actionId:string};
export async function assertReviewBodyPendingParentContract<P extends Pending>(input:{
 ctx:SessionContext;kind:string;prepare():Promise<P>;retire(row:P):Promise<unknown>;businessSnapshot():Promise<unknown>;
 terminalState?:'discarded'|'completed'|'expired'|'refused';retireTx?(tx:Tx,id:string):Promise<unknown>;
}){
 const target=await input.prepare();
 const [pending]=await owner.db.execute(sql`select r.state,r.action_kind,
  (select count(*)::int from app.assistant_own_leave_review_content c where c.action_id=r.id) bodies
  from app.assistant_own_leave_review r where r.id=${target.actionId}::uuid`);
 expect(pending).toMatchObject({state:'awaiting_confirmation',action_kind:input.kind,bodies:1});
 // Retire first so kinds with one-pending-per-subject do not need index bypass or a second subject.
 await input.retire(target);
 const source=await input.prepare();expect(source.actionId).not.toBe(target.actionId);
 const snapshot=async()=>{
  const rows=await owner.db.execute(sql`select to_jsonb(r) ledger,
   (select to_jsonb(c) from app.assistant_own_leave_review_content c where c.action_id=r.id) body
   from app.assistant_own_leave_review r where r.id in(${target.actionId}::uuid,${source.actionId}::uuid) order by r.id`);
  return {custody:Array.from(rows),business:await input.businessSnapshot()};
 };
 const initial=await snapshot();expect(initial.custody).toHaveLength(2);
 for(const row of initial.custody){expect(row.ledger).toMatchObject({action_kind:input.kind});
  const terminal=(row.ledger as {id:string}).id===target.actionId;
  expect(row.ledger).toMatchObject({state:terminal?(input.terminalState??'discarded'):'awaiting_confirmation'});
  if(terminal)expect(row.body).toBeNull();else expect(row.body).not.toBeNull();
 }
 const suffix=randomUUID().replaceAll('-',''),writer='fixture_body_write_'+suffix,hook='fixture_body_retarget_'+suffix,sequence='fixture_body_seen_'+suffix,
  trigger='zz_fixture_body_retarget_'+suffix;
 // A private fixture helper, never an application mutation API. It can only copy the selected
 // real pending source body; fixed IDs are generated by actual prepare adapters above.
 await owner.db.execute(sql.raw(`CREATE FUNCTION app.${writer}(operation text) RETURNS integer
 LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $fixture$
 DECLARE n integer;
 BEGIN
  IF operation='lock_parent' THEN
   PERFORM 1 FROM app.assistant_own_leave_review WHERE id='${source.actionId}'::uuid FOR UPDATE;RETURN 1;
  ELSIF operation='retired_probe' THEN
   SELECT count(*)::int INTO n FROM app.assistant_own_leave_review r WHERE r.id='${source.actionId}'::uuid
    AND r.state='discarded' AND NOT EXISTS(SELECT 1 FROM app.assistant_own_leave_review_content c WHERE c.action_id=r.id);RETURN n;
  ELSIF operation='pending_update' THEN
   UPDATE app.assistant_own_leave_review_content SET ciphertext=ciphertext WHERE action_id='${source.actionId}'::uuid;
  ELSIF operation='insert_terminal' THEN
   INSERT INTO app.assistant_own_leave_review_content SELECT '${target.actionId}'::uuid,kid,wrapped_dek,ciphertext FROM app.assistant_own_leave_review_content WHERE action_id='${source.actionId}'::uuid;
  ELSIF operation='update_terminal' THEN
   UPDATE app.assistant_own_leave_review_content SET action_id='${target.actionId}'::uuid WHERE action_id='${source.actionId}'::uuid;
  ELSIF operation='late_insert' THEN
   INSERT INTO app.assistant_own_leave_review_content SELECT action_id,kid,wrapped_dek,ciphertext FROM app.assistant_own_leave_review_content WHERE action_id='${source.actionId}'::uuid;
  ELSE RAISE EXCEPTION 'Unexpected fixture operation';END IF;
  GET DIAGNOSTICS n=ROW_COUNT;RETURN n;
 END $fixture$;
 REVOKE ALL ON FUNCTION app.${writer}(text) FROM PUBLIC;
 GRANT EXECUTE ON FUNCTION app.${writer}(text) TO ai_hr_app;`));
 const invoke=async(operation:string)=>withTenant(input.ctx,async tx=>{
  const [actor]=await tx.execute<{login:string;effective:string}>(sql`select session_user::text login,current_user::text effective`);
  expect(actor).toEqual({login:'ai_hr_app',effective:'ai_hr_app'});
  const [row]=await tx.execute<{n:number}>(sql`select ${sql.raw('app.'+writer)}(${operation}) n`);
  return row.n;
 });
 const reject=async(operation:string)=>{
  const before=await snapshot();let error:unknown;
  try{await invoke(operation);}catch(e){error=e;}
  expect(pgSqlState(error)).toBe('42501');
  // postgres-js may expose the native message on cause through Drizzle.
  const messages:unknown[]=[];for(let e=error;e&&typeof e==='object';e=(e as {cause?:unknown}).cause)messages.push((e as {message?:unknown}).message);
  expect(messages.some(message=>typeof message==='string'&&message===refusal)).toBe(true);
  expect(await snapshot()).toEqual(before);
 };
 try{
  // A successful real prepare already passed INSERT fences. This actual app invocation proves
  // pending UPDATE reaches one nonempty physical row and leaves all content/ledger values intact.
  expect(await invoke('pending_update')).toBe(1);expect(await snapshot()).toEqual(initial);
  if(input.retireTx){
   const retireTx=input.retireTx,rollback=Error('fixture canonical retirement rollback');
   const deferred=()=>{let resolve!:()=>void;const promise=new Promise<void>(r=>{resolve=r;});return{promise,resolve};};
   const assertBusy=(error:unknown)=>{expect(pgSqlState(error)).toBe('55P03');};
   // Parent first: actual app session invokes owner fixture lock; body writer must fail NOWAIT,
   // then the actual native retirement runs, positively retires/deletes, and is explicitly rolled back.
   {
    const before=await snapshot(),parentReady=deferred(),bodyDone=deferred();
    const retirement=withTenant(input.ctx,async tx=>{
     await tx.execute(sql`set local statement_timeout='5s'`);
     await tx.execute(sql`select ${sql.raw('app.'+writer)}('lock_parent')`);parentReady.resolve();
     await bodyDone.promise;await retireTx(tx,source.actionId);
     const [state]=await tx.execute<{n:number}>(sql`select ${sql.raw('app.'+writer)}('retired_probe') n`);
     expect(state.n).toBe(1);throw rollback;
    }).then(()=>{throw Error('retirement must rollback');},error=>{if(error!==rollback)throw error;});
    let bodyError:unknown;
    try{await Promise.race([parentReady.promise,retirement.then(()=>{throw Error('retirement ended before parent lock');})]);try{await invoke('pending_update');}catch(error){bodyError=error;}}
    finally{bodyDone.resolve();await retirement;}
    assertBusy(bodyError);expect(await snapshot()).toEqual(before);
   }
   // Body first: owner A holds actual body row, canonical app retirement B locks parent then waits
   // for A's body. Observe the actual blocking edge, then A's UPDATE must abort with55P03, releasing
   // the tuple so B can finish its canonical path and explicitly roll back. No deadlock retry/catch.
   {
    const before=await snapshot(),bodyLocked=deferred(),tryUpdate=deferred();let bodyPid=0,retirePid=0;
    const body=owner.db.transaction(async tx=>{
     await tx.execute(sql`set local statement_timeout='5s'`);
     const [pid]=await tx.execute<{pid:number}>(sql`select pg_backend_pid() pid`);bodyPid=pid.pid;
     await tx.execute(sql`select 1 from app.assistant_own_leave_review_content where action_id=${source.actionId}::uuid for update`);bodyLocked.resolve();
     await tryUpdate.promise;await tx.execute(sql`update app.assistant_own_leave_review_content set ciphertext=ciphertext where action_id=${source.actionId}::uuid`);
    }).then(()=>{throw Error('body lock inversion must refuse');},error=>{assertBusy(error);});
    await Promise.race([bodyLocked.promise,body.then(()=>{throw Error('body writer ended before tuple lock');})]);
    const retirement=withTenant(input.ctx,async tx=>{
     await tx.execute(sql`set local statement_timeout='5s'`);const [pid]=await tx.execute<{pid:number}>(sql`select pg_backend_pid() pid`);retirePid=pid.pid;
     await retireTx(tx,source.actionId);const [state]=await tx.execute<{n:number}>(sql`select ${sql.raw('app.'+writer)}('retired_probe') n`);expect(state.n).toBe(1);throw rollback;
    }).then(()=>{throw Error('retirement must rollback');},error=>{if(error!==rollback)throw error;});
    let blocked=false;
    try{
     for(let attempt=0;attempt<80;attempt++){
      if(retirePid){const [edge]=await owner.db.execute<{blocked:boolean}>(sql`select ${bodyPid}::int=any(pg_blocking_pids(${retirePid}::int)) blocked`);if(edge.blocked){blocked=true;break;}}
      await new Promise(resolve=>setTimeout(resolve,10));
     }
    }finally{tryUpdate.resolve();await Promise.all([body,retirement]);}
    expect(blocked,'actual canonical retirement must wait on the held content tuple').toBe(true);expect(await snapshot()).toEqual(before);
   }
  }
  await reject('insert_terminal');await reject('update_terminal');
  // A unique test-only sequence is a nontransactional reachability witness: nextval survives the
  // rejected DML rollback. It is not a production ledger, grant or GUC-based authorization source.
  await owner.db.execute(sql.raw(`CREATE SEQUENCE app.${sequence};
   CREATE FUNCTION app.${hook}() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
   SET search_path=pg_catalog,public,pg_temp AS $fixture$ BEGIN
    IF NEW.action_id='${source.actionId}'::uuid THEN PERFORM nextval('app.${sequence}');NEW.action_id:='${target.actionId}'::uuid;END IF;RETURN NEW;
   END $fixture$;
   CREATE TRIGGER ${trigger} BEFORE INSERT OR UPDATE ON app.assistant_own_leave_review_content
   FOR EACH ROW EXECUTE FUNCTION app.${hook}();`));
  for(const operation of ['late_insert','pending_update']){
   const [before]=await owner.db.execute<{value:string}>(sql.raw(`select nextval('app.${sequence}')::text value`));
   await reject(operation);
   const [after]=await owner.db.execute<{value:string}>(sql.raw(`select last_value::text value from app.${sequence}`));
   expect(BigInt(after.value)).toBe(BigInt(before.value)+BigInt(1));
  }
 }finally{
  await owner.db.execute(sql.raw(`DROP TRIGGER IF EXISTS ${trigger} ON app.assistant_own_leave_review_content;
   DROP FUNCTION IF EXISTS app.${hook}();DROP FUNCTION IF EXISTS app.${writer}(text);DROP SEQUENCE IF EXISTS app.${sequence};`));
 }
}
