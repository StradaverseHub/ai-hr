import {randomUUID} from 'node:crypto';
import {afterAll,beforeAll,expect,it} from 'vitest';
import {sql} from 'drizzle-orm';
import {closeAll,migrateTestDb,owner} from './harness';
import {readContractSharedLetter,actContractSharedLetter} from '../packs/contracts/service';
import {readContractSharedForm} from '../core/contract-shared-form';
import {formFixture,visible,saveAnswers,actForm} from './helpers/contract-document-fixture';
beforeAll(migrateTestDb);afterAll(closeAll);
it('returns a signed Form to its actual owner, refreshes unlocked Personnel values and requires every new-round signature',async()=>{
 const f=await formFixture();
 await saveAnswers(f.admin,f.letterId,{hrChoice:'Yes'});
 await actForm(f.admin,f.letterId,'reviewed');
 await actForm(f.admin,f.letterId,'signed');
 const original=visible(await readContractSharedForm(f.employeeActor,f.letterId));
 expect(original.values.lockedBank).toBe('FICTIONAL-BANK-001');
 const beforeReturn=await readContractSharedLetter(f.employeeActor,f.letterId);
 const returned=await actContractSharedLetter(f.employeeActor,{id:f.letterId,actionId:randomUUID(),stepId:beforeReturn.pendingAction!.stepId,revision:beforeReturn.contentRevision,hash:beforeReturn.contentHash!,action:'returned',comment:'Please correct the Personnel bank source before I sign.'});
 expect(returned.returned).toBe(true);expect(returned.valuesFixed).toBe(false);
 const ownerLetter=await readContractSharedLetter(f.admin,f.letterId);
 expect(ownerLetter.canResend).toBe(true);expect(ownerLetter.canEdit).toBe(true);
 expect((await readContractSharedLetter(f.employeeActor,f.letterId)).pendingAction).toBeNull();
 await owner.db.execute(sql`update employee_statutory_my set bank_account_no='FICTIONAL-CORRECTED-BANK' where tenant_id=${f.b.tenantId}::uuid and person_id=${f.employee.personId}::uuid`);
 const corrected=visible(await readContractSharedForm(f.admin,f.letterId));
 expect(corrected.values.lockedBank).toBe('FICTIONAL-CORRECTED-BANK');
 const current=await readContractSharedLetter(f.admin,f.letterId);
 await actContractSharedLetter(f.admin,{id:f.letterId,actionId:randomUUID(),stepId:current.layers.find(layer=>layer.owner)!.id,revision:current.contentRevision,hash:current.contentHash!,action:'resent',comment:'Personnel correction verified; please review the new round.'});
 expect((await readContractSharedLetter(f.admin,f.letterId)).pendingAction?.kind).toBe('review');
 expect((await readContractSharedLetter(f.employeeActor,f.letterId)).pendingAction).toBeNull();
 await actForm(f.admin,f.letterId,'reviewed');await actForm(f.admin,f.letterId,'signed');
 const waiting=await readContractSharedLetter(f.employeeActor,f.letterId);
 expect(waiting.state).toBe('routing');expect(waiting.pendingAction?.kind).toBe('sign');
 await saveAnswers(f.employeeActor,f.letterId,{employeeAck:'true',employeeRows:'[["Fictional","Corrected"]]'});
 expect((await actForm(f.employeeActor,f.letterId,'signed')).state).toBe('released');
 const final=visible(await readContractSharedForm(f.employeeActor,f.letterId));
 expect(final.values.lockedBank).toBe('FICTIONAL-CORRECTED-BANK');
 for(const receipt of original.receipts)expect(final.receipts).toContainEqual(receipt);
 expect(final.receipts.filter(receipt=>receipt.scope==='hr')).toHaveLength(4);
});
