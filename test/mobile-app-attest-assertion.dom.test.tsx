import {createHash,createPublicKey,generateKeyPairSync,sign} from 'node:crypto';
import {decodeFirstSync,encode,Tagged} from 'cbor';
import {describe,expect,it} from 'vitest';
import fixture from './fixtures/mobile-integrity/node-app-attest-assertion.json';
import {AppAttestAssertionError,checkAppAttestAssertion} from '../lib/mobile-api/app-attest-assertion';

const reference=()=>({assertion:Buffer.from(fixture.assertion,'base64'),clientData:Buffer.from(fixture.payload),
  publicKey:createPublicKey(fixture.publicKey),appId:fixture.appId,previousCounter:0});
function reason(fn:()=>unknown,expected:string){
  try{fn();throw new Error('Expected assertion refusal');}
  catch(error){expect(error).toBeInstanceOf(AppAttestAssertionError);expect(error).toMatchObject({reason:expected,message:'App Attest assertion check failed'});}
}
function synthetic(counter:number){
  const original=reference(),{privateKey,publicKey}=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
  const authenticatorData=Buffer.alloc(37);createHash('sha256').update(original.appId).digest().copy(authenticatorData);
  authenticatorData[32]=0x40;authenticatorData.writeUInt32BE(counter,33);
  const nonce=createHash('sha256').update(authenticatorData).update(createHash('sha256').update(original.clientData).digest()).digest();
  const signature=sign('sha256',nonce,privateKey);
  return {...original,publicKey,assertion:encode({signature,authenticatorData})};
}
describe('server App Attest assertion proof checker',()=>{
  it('interoperates with a pinned public upstream assertion rather than only signatures generated by this test',()=>{
    expect(checkAppAttestAssertion(reference())).toEqual({nextCounter:1});
  });
  it('rejects altered client bytes, wrong app identity and a different public key',()=>{
    const original=reference();
    reason(()=>checkAppAttestAssertion({...original,clientData:Buffer.from('SYNTHETIC_PRIVATE_VALUE')}),'invalid_signature');
    reason(()=>checkAppAttestAssertion({...original,appId:'V8H6LQ9448.io.other.App'}),'wrong_app');
    reason(()=>checkAppAttestAssertion({...original,publicKey:synthetic(1).publicKey}),'invalid_signature');
  });
  it('requires a strictly increasing unsigned counter, including values above signed 32-bit range',()=>{
    const original=reference();
    for(const previousCounter of [1,10,0xffffffff])reason(()=>checkAppAttestAssertion({...original,previousCounter}),'replayed_counter');
    reason(()=>checkAppAttestAssertion(synthetic(0)),'replayed_counter');
    expect(checkAppAttestAssertion({...synthetic(0x80000000),previousCounter:0x7fffffff})).toEqual({nextCounter:0x80000000});
    expect(checkAppAttestAssertion(synthetic(0xffffffff))).toEqual({nextCounter:0xffffffff});
  });
  it('requires an explicit stored counter and a P-256 public key, never a supplied private or other-curve key',()=>{
    const original=reference(),pair=generateKeyPairSync('ec',{namedCurve:'secp384r1'});
    for(const previousCounter of [undefined,-1,0.5,NaN,0x100000000])reason(()=>checkAppAttestAssertion({...original,previousCounter:previousCounter as number}),'invalid_configuration');
    for(const publicKey of [pair.publicKey,pair.privateKey,fixture.publicKey])reason(()=>checkAppAttestAssertion({...original,publicKey:publicKey as typeof original.publicKey}),'invalid_key');
  });
  it('rejects trailing CBOR, duplicate keys and unexpected map fields',()=>{
    const original=reference(),decoded=decodeFirstSync(original.assertion),{signature,authenticatorData}=decoded;
    const duplicate=Buffer.concat([Buffer.from([0xa3]),encode('signature'),encode(signature),encode('signature'),encode(signature),encode('authenticatorData'),encode(authenticatorData)]);
    for(const assertion of [Buffer.concat([original.assertion,Buffer.from([0])]),duplicate,
      encode({...decoded,verified:true}),encode({signature,other:authenticatorData}),encode([signature,authenticatorData])])
      reason(()=>checkAppAttestAssertion({...original,assertion}),'malformed');
  });
  it('rejects semantic tags and excessive nesting instead of running general CBOR conversions',()=>{
    const original=reference(),decoded=decodeFirstSync(original.assertion);
    let nested:unknown=decoded;for(let i=0;i<8;i++)nested=[nested];
    for(const value of [new Tagged(259,new Map(Object.entries(decoded))),
      {...decoded,signature:new Tagged(64,decoded.signature)},nested])
      reason(()=>checkAppAttestAssertion({...original,assertion:encode(value)}),'malformed');
  });
  it('bounds buffers and rejects truncated, extended or mistyped authenticator/signature fields',()=>{
    const original=reference(),decoded=decodeFirstSync(original.assertion);
    for(const assertion of [Buffer.alloc(0),Buffer.alloc(8193),original.assertion.subarray(0,10),
      encode({...decoded,authenticatorData:decoded.authenticatorData.subarray(0,36)}),
      encode({...decoded,authenticatorData:Buffer.concat([decoded.authenticatorData,Buffer.from([0])])}),
      encode({...decoded,signature:decoded.signature.toString('base64')}),
      encode({...decoded,signature:Buffer.concat([decoded.signature,Buffer.from([0])])})])
      reason(()=>checkAppAttestAssertion({...original,assertion}),'malformed');
    for(const clientData of [Buffer.alloc(0),Buffer.alloc(16385)])reason(()=>checkAppAttestAssertion({...original,clientData}),'malformed');
  });
  it('does not return vendor trust, enrollment identity, payroll acceptance or an advanced persisted counter',()=>{
    const original=reference(),result=checkAppAttestAssertion(original);
    expect(result).toEqual({nextCounter:1});expect(original.previousCounter).toBe(0);
    // A pure proof check does not consume anything: a transaction owner must serialize and persist.
    expect(checkAppAttestAssertion(original)).toEqual(result);
  });
});
