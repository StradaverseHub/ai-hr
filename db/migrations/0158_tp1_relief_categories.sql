-- TP1 Relief structured per-category breakdown (feedback a2f1fa24 "TP1 Relief Function – Conversion
-- from PDF Form to interactive"). ADR-00XX extends ADR-0050.
--
-- The reporter's ask: the LHDN paper TP1 form is organised category by category (individual, spouse,
-- children, parent, medical/insurance, lifestyle, ...), but the system captured only ONE opaque annual
-- scalar (`tp1_amount`). This migration adds an OPTIONAL JSONB `categories` column so the same
-- append-only tp1_relief row can hold the per-category breakdown alongside the scalar roll-up.
--
-- Load-bearing decision (ADR-0050 golden-path preservation): `tp1_amount` STAYS the authoritative,
-- server-computed SUM of the categories and remains the ONLY value the PCB kernel consumes
-- (prefillTp1FromSelfRelief reads tp1_relief.tp1_amount). The kernel math is therefore untouched: a row
-- with `categories` NULL and a scalar amount behaves exactly as before (backward compatible), and a row
-- with categories has `tp1_amount = round2(sum(categories))`. Nothing about monthly MTD changes.
--
-- Shape of the JSONB payload (all optional numeric fields + a free-text remark):
--   { "individual": 9000, "spouse": 0, "children": 4000, "parent": 0,
--     "medicalInsurance": 0, "lifestyle": 2500, "education": 0, "other": 0, "remarks": "..." }
-- The JSONB extension point lets new categories be added later without a migration (repo convention).
--
-- PDPA Layer-0 (ADR-0030) unchanged: the category amounts live ONLY on this RLS-protected row; the
-- tp1.* DomainEvent payloads still reference row id + year + changed FIELD names, never cleartext values.
--
-- No RLS change: tp1_relief already has the app.can_see_person (self + admin) read/write policy
-- (`tp1_relief_rls`); a bare ADD COLUMN inherits the table's existing row-level policy (same pattern as
-- 0133 backdating_limit_days, 0147 custom_messages, 0155 leave_type_expiry). No grant re-declaration.
--
-- Additive + idempotent: IF NOT EXISTS guard, nullable column, no default backfill. Existing rows keep
-- `categories` NULL and their scalar tp1_amount.
--
-- Journal entry: idx 157 (see meta/_journal.json). PLACEHOLDER NUMBER — the integration step may renumber
-- this migration; it is self-contained and idempotent, so the exact index is not load-bearing.
ALTER TABLE "tp1_relief" ADD COLUMN IF NOT EXISTS "categories" jsonb;
